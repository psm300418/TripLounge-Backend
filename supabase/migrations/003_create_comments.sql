-- 댓글 권한 판정에 필요한 기반 테이블을 먼저 적용해야 하는 설정
do $$ begin
  if to_regclass('public.posts') is null or to_regclass('public.post_members') is null then
    raise exception 'post tables must be installed before comment migration';
  end if;
  if to_regclass('public.users') is null then
    raise exception 'public.users must be installed before comment migration';
  end if;
  if to_regclass('public.user_friends') is null then
    raise exception 'public.user_friends must be installed before comment migration';
  end if;
end $$;

-- 댓글 모듈에서 게시글 공개 범위를 독립적으로 확인하는 함수
create or replace function private.comment_can_view_post(p_post_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null
    and exists (
      select 1
      from public.posts p
      where p.id = p_post_id
        and (
          p.user_id = auth.uid()
          or p.visibility = 'PUBLIC'
          or (
            p.visibility = 'FRIENDS'
            and exists (
              select 1
              from public.user_friends f
              where f.user_id = least(auth.uid(), p.user_id)
                and f.friend_id = greatest(auth.uid(), p.user_id)
            )
          )
          or (
            p.visibility = 'MEMBERS_ONLY'
            and exists (
              select 1
              from public.post_members m
              where m.post_id = p.id
                and m.user_id = auth.uid()
            )
          )
        )
    );
$$;

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  parent_comment_id bigint,
  content text not null check (char_length(btrim(content)) between 1 and 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (id, post_id),
  foreign key (parent_comment_id, post_id)
    references public.comments(id, post_id) on delete cascade
);

create index if not exists comments_post_created_idx
  on public.comments(post_id, created_at, id);
create index if not exists comments_user_created_idx
  on public.comments(user_id, created_at desc);

alter table public.comments enable row level security;
revoke all on public.comments from anon, authenticated;
grant select (id, post_id, parent_comment_id, content, created_at, updated_at, deleted_at)
  on public.comments to authenticated;

-- 접근 가능한 게시글의 댓글만 직접 조회할 수 있게 제한하는 정책
drop policy if exists tl_comments_read_allow on public.comments;
create policy tl_comments_read_allow on public.comments
  for select to authenticated using (private.comment_can_view_post(post_id));
drop policy if exists tl_comments_read_guard on public.comments;
create policy tl_comments_read_guard on public.comments as restrictive
  for select to authenticated using (private.comment_can_view_post(post_id));

-- 댓글 목록과 제한된 작성자 프로필 반환
create or replace function public.list_post_comments(
  p_post_id bigint,
  p_limit int default 20,
  p_offset int default 0
) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_result jsonb;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_post_id is null or p_post_id <= 0 or p_limit is null or p_limit not between 1 and 50
     or p_offset is null or p_offset not between 0 and 500000 then
    raise exception 'INVALID_REQUEST';
  end if;
  if not private.comment_can_view_post(p_post_id) then raise exception 'POST_NOT_FOUND'; end if;

  with visible_comments as (
    select c.id, c.content, c.created_at, c.updated_at, c.deleted_at,
      c.user_id, u.nickname, u.avatar_url
    from public.comments c
    left join public.users u on u.id = c.user_id and c.deleted_at is null
    where c.post_id = p_post_id and c.parent_comment_id is null
  ), page as (
    select * from visible_comments order by created_at, id limit p_limit offset p_offset
  )
  select jsonb_build_object(
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', id,
        'content', case when deleted_at is null then content else '삭제된 댓글입니다.' end,
        'createdAt', created_at,
        'updatedAt', updated_at,
        'deletedAt', deleted_at,
        'author', case when deleted_at is null then
          jsonb_build_object('nickname', nickname, 'avatarUrl', avatar_url)
          else null end,
        'isMine', user_id = auth.uid()
      ) order by created_at, id) from page
    ), '[]'::jsonb),
    'total', (select count(*) from visible_comments),
    'limit', p_limit,
    'offset', p_offset
  ) into v_result;

  return v_result;
end;
$$;

-- 댓글 작성
create or replace function public.create_post_comment(
  p_post_id bigint,
  p_user_id uuid,
  p_content text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_comment public.comments; v_nickname text; v_avatar_url text; v_content text;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_user_id is distinct from auth.uid() then raise exception 'FORBIDDEN'; end if;
  if p_post_id is null or p_post_id <= 0 or p_content is null then raise exception 'INVALID_REQUEST'; end if;
  v_content := btrim(p_content);
  if char_length(v_content) not between 1 and 2000 then raise exception 'INVALID_REQUEST'; end if;
  if not private.comment_can_view_post(p_post_id) then raise exception 'POST_NOT_FOUND'; end if;

  insert into public.comments(post_id, user_id, content)
    values (p_post_id, auth.uid(), v_content)
    returning * into v_comment;
  select nickname, avatar_url into v_nickname, v_avatar_url
    from public.users where id = auth.uid();

  return jsonb_build_object(
    'id', v_comment.id,
    'content', v_comment.content,
    'createdAt', v_comment.created_at,
    'updatedAt', v_comment.updated_at,
    'deletedAt', null,
    'author', case when v_nickname is null then null
      else jsonb_build_object('nickname', v_nickname, 'avatarUrl', v_avatar_url) end,
    'isMine', true
  );
end;
$$;

-- 본인이 작성했고 아직 삭제되지 않은 댓글만 수정
create or replace function public.update_post_comment(
  p_comment_id bigint,
  p_user_id uuid,
  p_content text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_comment public.comments; v_nickname text; v_avatar_url text; v_content text;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_user_id is distinct from auth.uid() then raise exception 'FORBIDDEN'; end if;
  if p_comment_id is null or p_comment_id <= 0 or p_content is null then raise exception 'INVALID_REQUEST'; end if;
  v_content := btrim(p_content);
  if char_length(v_content) not between 1 and 2000 then raise exception 'INVALID_REQUEST'; end if;

  select * into v_comment from public.comments where id = p_comment_id for update;
  if not found then return null; end if;
  if not private.comment_can_view_post(v_comment.post_id) then raise exception 'POST_NOT_FOUND'; end if;
  if v_comment.user_id <> auth.uid() or v_comment.deleted_at is not null then return null; end if;

  update public.comments set content = v_content, updated_at = now()
    where id = p_comment_id returning * into v_comment;
  select nickname, avatar_url into v_nickname, v_avatar_url
    from public.users where id = auth.uid();

  return jsonb_build_object(
    'id', v_comment.id,
    'content', v_comment.content,
    'createdAt', v_comment.created_at,
    'updatedAt', v_comment.updated_at,
    'deletedAt', null,
    'author', case when v_nickname is null then null
      else jsonb_build_object('nickname', v_nickname, 'avatarUrl', v_avatar_url) end,
    'isMine', true
  );
end;
$$;

-- 본인이 작성한 댓글의 내용을 숨기고 삭제 시각 기록
create or replace function public.soft_delete_post_comment(
  p_comment_id bigint,
  p_user_id uuid
) returns boolean
language plpgsql security definer set search_path = '' as $$
declare v_comment public.comments;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_user_id is distinct from auth.uid() then raise exception 'FORBIDDEN'; end if;
  if p_comment_id is null or p_comment_id <= 0 then raise exception 'INVALID_REQUEST'; end if;

  select * into v_comment from public.comments where id = p_comment_id for update;
  if not found then return false; end if;
  if not private.comment_can_view_post(v_comment.post_id) then raise exception 'POST_NOT_FOUND'; end if;
  if v_comment.user_id <> auth.uid() or v_comment.deleted_at is not null then return false; end if;

  update public.comments set content = '삭제된 댓글입니다.', deleted_at = now(), updated_at = now()
    where id = p_comment_id;
  return true;
end;
$$;

