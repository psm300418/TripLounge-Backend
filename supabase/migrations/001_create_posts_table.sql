-- 기존 테이블이 있다면 완전히 삭제 (초기화)
DROP TABLE IF EXISTS post_photos CASCADE;
DROP TABLE IF EXISTS post_days CASCADE;
DROP TABLE IF EXISTS post_members CASCADE;
DROP TABLE IF EXISTS posts CASCADE;

-- 공개범위 Enum 타입 생성 (이미 있으면 재사용)
DO $$ BEGIN
    CREATE TYPE post_visibility AS ENUM ('PUBLIC', 'FRIENDS', 'MEMBERS_ONLY', 'PRIVATE');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- [게시글 메인] 전체 여행 정보
CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    visibility post_visibility NOT NULL DEFAULT 'PUBLIC',
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- [동행 친구] 함께 간 친구 목록
CREATE TABLE post_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id UUID NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- [일차별 일기] 일차별 제목과 본문
CREATE TABLE post_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    day_number INT NOT NULL,               -- 1일차, 2일차
    date DATE NOT NULL,                     -- 2026-10-01
    title VARCHAR(255) NOT NULL,            -- 해당 일차 제목
    content TEXT NOT NULL,                  -- 해당 일차 본문 (서식 HTML/JSON)
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- [사진] 각 일차에 첨부된 사진들과 마커 좌표
CREATE TABLE post_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_day_id BIGINT NOT NULL REFERENCES post_days(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,                -- Supabase Storage 업로드 URL
    taken_at TIMESTAMPTZ,                   -- 메타데이터에서 가져온 시간 (수정 가능)
    place_name VARCHAR(255),                -- 메타데이터/카카오에서 가져온 장소명
    address VARCHAR(255),                   -- 상세 주소
    latitude DOUBLE PRECISION,              -- 위도
    longitude DOUBLE PRECISION,             -- 경도
    order_index INT DEFAULT 0 NOT NULL,     -- 사진 표시 순서
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 4개 테이블 RLS 보안 잠금 활성화
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE post_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE post_days ENABLE ROW LEVEL SECURITY;
ALTER TABLE post_photos ENABLE ROW LEVEL SECURITY;

-- 기존 정책 초기화 (재실행 시 충돌 방지)
DROP POLICY IF EXISTS "게시글 읽기 권한" ON posts;
DROP POLICY IF EXISTS "게시글 작성 권한" ON posts;
DROP POLICY IF EXISTS "게시글 수정 권한" ON posts;
DROP POLICY IF EXISTS "게시글 삭제 권한" ON posts;
DROP POLICY IF EXISTS "게시글 전체 접근" ON posts;
DROP POLICY IF EXISTS "동행 멤버 관리 권한" ON post_members;
DROP POLICY IF EXISTS "일차별 일기 관리 권한" ON post_days;
DROP POLICY IF EXISTS "사진 관리 권한" ON post_photos;

-- 테스트용: 로그인 없이 게시글 전체 작업 가능
CREATE POLICY "게시글 전체 접근" ON posts
    FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

-- 하위 테이블 보안 정책 (post_members, post_days, post_photos)
CREATE POLICY "동행 멤버 관리 권한" ON post_members
    FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

CREATE POLICY "일차별 일기 관리 권한" ON post_days
    FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

CREATE POLICY "사진 관리 권한" ON post_photos
    FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON posts, post_members, post_days, post_photos TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
