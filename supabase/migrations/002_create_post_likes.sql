-- 게시글별 좋아요
CREATE TABLE public.post_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT post_likes_post_user_key UNIQUE (post_id, user_id)
);

CREATE INDEX post_likes_user_id_idx ON public.post_likes(user_id);

ALTER TABLE public.post_likes ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, DELETE ON public.post_likes TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.post_likes_id_seq TO authenticated;

-- 게시글을 조회할 수 있는 사용자만 좋아요 정보 확인 가능
CREATE POLICY "Users can read likes on visible posts"
  ON public.post_likes
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.posts
      WHERE posts.id = post_likes.post_id
    )
  );

-- 인증된 사용자는 본인 이름으로만 좋아요를 등록 가능
CREATE POLICY "Users can like visible posts as themselves"
  ON public.post_likes
  FOR INSERT
  TO authenticated
  WITH CHECK (
    user_id = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1
      FROM public.posts
      WHERE posts.id = post_likes.post_id
    )
  );

-- 사용자는 본인의 좋아요만 취소 가능
CREATE POLICY "Users can remove their own likes"
  ON public.post_likes
  FOR DELETE
  TO authenticated
  USING (user_id = (SELECT auth.uid()));
